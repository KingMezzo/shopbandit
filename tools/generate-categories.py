"""Generate offline dictionary in Dart and PocketBase JS from one reviewed source.

Run with --check in CI. The released migration snapshot must never be regenerated.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'tools/category_dictionary.json').read_text(encoding='utf-8'))


def normalize(s):
    s = s.lower().translate(str.maketrans({'ä': 'ae', 'ö': 'oe', 'ü': 'ue', 'ß': 'ss', 'é': 'e', 'è': 'e'}))
    return re.sub(r'[\s\-]+', ' ', s).strip()


words = {}
for key, category in data.items():
    for word in filter(None, category['products'].split('|')):
        word = normalize(word)
        if word in words and words[word] != key:
            raise ValueError(f'Ambiguous dictionary entry: {word}')
        words[word] = key
definitions = [{"key": k, "icon": v['icon'], "color": v['color']} for k, v in data.items()]
for locale in ('de', 'en'):
    arb = json.loads((ROOT / f'app/lib/l10n/app_{locale}.arb').read_text(encoding='utf-8'))
    for key, category in data.items():
        label = 'category' + ''.join(part.capitalize() for part in key.split('_'))
        if arb.get(label) != category[locale]:
            raise SystemExit(f'Default translation differs from dictionary: {locale}/{label}')
dart = "// Generated by tools/generate-categories.py. Edit the JSON source.\nconst productDictionary = <String, String>{\n" + ''.join(f'  {word!r}: {key!r},\n' for word, key in words.items()) + '};\n'
js = "// Generated by tools/generate-categories.py. Edit the JSON source.\nmodule.exports = " + json.dumps({'defaults': definitions, 'words': words}, ensure_ascii=False, indent=2) + "\n"
outputs = {'app/lib/core/product_dictionary.dart': dart, 'server/pb_hooks/category_data.js': js}
for path, content in outputs.items():
    target = ROOT / path
    if '--check' in sys.argv:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            raise SystemExit(f'Outdated generated dictionary: {path}')
    else:
        target.write_text(content, encoding='utf-8')
print(f'{len(words)} safe exact names/synonyms; {len(data)} categories')
